// Write .env.local for the local stack: the local API URL and the anon key from supabase status.
// The service-role key is never read or written here.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

let status = '';
try {
  status = execFileSync('supabase', ['status', '-o', 'env'], { encoding: 'utf8' });
} catch {
  console.error('Could not run supabase status. Is the local stack running? Try supabase start.');
  process.exit(1);
}

const match = status.match(/^ANON_KEY="?(.*?)"?$/m);
const anonKey = match ? match[1] : '';
if (!anonKey) {
  console.error('supabase status printed no ANON_KEY. Start the stack with supabase start.');
  process.exit(1);
}

const body = [
  '# Local only. Generated by pnpm env:local from the running Supabase stack.',
  '# The app uses the anon key and the signed-in user. No service-role key belongs here.',
  'NEXT_PUBLIC_SUPABASE_URL=http://localhost:54321',
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  '',
].join('\n');

writeFileSync('.env.local', body, 'utf8');
console.log('wrote .env.local with the local API URL and the anon key');
